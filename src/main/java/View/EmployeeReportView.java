    private void btnGenerateEmployeeFinancialReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateEmployeeFinancialReportActionPerformed
        try (Connection conn = DatabaseConnectionUtil.getConnection()) {
            ReportGeneratorUtil generator = new ReportGeneratorUtil();
            generator.generateReport(conn, ReportType.EmployeeFinancial);

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Something went wrong : " + ex.getMessage(), "ERROR", JOptionPane.ERROR_MESSAGE);
            Logger.getLogger(EmployeeReportView.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnGenerateEmployeeFinancialReportActionPerformed

