    private void jToggleButtonPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButtonPasswordActionPerformed
    // Check the state of the toggle button
    if (jToggleButtonPassword.isSelected()) {
        // If the button is selected, show the password
        jPasswordField.setEchoChar((char) 0); // Set echo character to null
        jToggleButtonPassword.setText("Hide Password"); // Change button text
    } else {
        // If the button is not selected, hide the password
        jPasswordField.setEchoChar('*'); // Set echo character back to '*'
        jToggleButtonPassword.setText("Show Password"); // Change button text
    }
    }//GEN-LAST:event_jToggleButtonPasswordActionPerformed

