    public final void populateAccessControlTable(Integer searchFieldEmployeeId) {

        try {

                // Check if employee ID is provided for filtering
                if (searchFieldEmployeeId != null) {
                    accessControlRecords = userIt.getEmployeeById(searchFieldEmployeeId); // Fetch filtered records
                } else {
                    accessControlRecords = userIt.getAllEmployees(); // Fetch all records
                }

            for (Employee record : accessControlRecords) {

                System.out.println(record.toString());

            }

            String[] columnNamesAccessControl = {
                "Employee ID", "First Name", "Last Name", "Employment Status",
                "Position", "User Role"

            };

            DefaultTableModel tableModelAccessControl = TableModelUtil.createReadOnlyTableModel(
                    accessControlRecords,
                    columnNamesAccessControl,
                    record -> new Object[]{
                        record.getEmpId(),
                        record.getFirstName(),
                        record.getLastName(),
                        record.getEmpStatus(),
                        record.getPositionSalaryHistory().getJobPosition().getTitle(),
                        record.getUserRole()

                    }
            );

            tblAccessControl.setModel(tableModelAccessControl);

            // Add a ListSelectionListener to the table
            tblAccessControl.getSelectionModel().addListSelectionListener(event -> {

                if (!event.getValueIsAdjusting()) { // Only respond when the selection is final

                    int selectedRow = tblAccessControl.getSelectedRow();

                    if (selectedRow != -1) { // Check if a row is selected

                        // Get the selected employee record
                        Employee selectedEmployee = accessControlRecords.get(selectedRow);

                        // Update text fields with the selected employee's data
                        fieldEmployeeId.setText(String.valueOf(selectedEmployee.getEmpId()));

                        fieldUserRole.setText(selectedEmployee.getUserRole().toString());

                    }

                }

            });

            // Apply the custom cell renderer to all columns
            tblAccessControl.setDefaultRenderer(Object.class, new ZebraStripingCellRenderer());

            // Customize the table header background
            tblAccessControl.getTableHeader().setBackground(ColorTheme.DARK); // Darker background

            tblAccessControl.getTableHeader().setForeground(Color.WHITE); // White text

            fieldEmployeeId.setEditable(false);

            fieldUserRole.setEditable(false);

        } catch (Exception ex) {

            Logger.getLogger(EmployeeDashboardView.class.getName()).log(Level.SEVERE, null, ex);

        }

    }

